export function inferLanguage(env = process.env) {
  return /^zh(?:[_-]|$)/iu.test(env.LC_ALL ?? env.LC_MESSAGES ?? env.LANG ?? "") ? "zh-CN" : "en";
}

export function translator(language = "en") {
  const dictionary = messages[LANGUAGES.includes(language) ? language : "en"];
  return (key, values = {}) => {
    let value = dictionary[key] ?? messages.en[key] ?? key;
    for (const [name, replacement] of Object.entries(values)) value = value.replaceAll(`{${name}}`, replacement);
    return value;
  };
}
